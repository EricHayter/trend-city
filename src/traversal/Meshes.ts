/**
 * Meshes — every piece of traversal geometry, generated in code.
 *
 * Nothing here is loaded, nothing here is PBR, and nothing here reaches the
 * scene without going through `finalizeGeometry`. That last one is not a style
 * note: the inverted-hull outline reads `aSmoothNormal` and `aCurvature`, and a
 * geometry that skipped the weld draws with a torn hull at every hard edge and
 * full stroke weight everywhere — the documented "exploded mesh" defect.
 *
 * DRAW-CALL BUDGET
 *
 * A course-length rail network is hundreds of objects and the main pass is
 * already the frame's cost centre, so furniture is merged into CHUNKS of route
 * distance — one mesh per (material, chunk) — and whole chunks are switched off
 * by `setWindow` as the player moves. That gives coarse culling that actually
 * removes draw calls, which per-object frustum culling on a merged mesh cannot.
 */

