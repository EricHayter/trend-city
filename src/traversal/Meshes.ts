export type RampName = keyof typeof RAMPS;

// ─────────────────────────────────────────────────────────────────────────────
// Merge
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Concatenate geometries that share a material. Position/normal/uv only —
 * everything the cel pipeline needs beyond that is generated by
 * `finalizeGeometry` AFTER the merge, which is also the only way the weld can
 * see across the seam between two merged parts.
 */
export function mergeGeos(parts: BufferGeometry[]): BufferGeometry {
  let vcount = 0;
  let icount = 0;
  for (const p of parts) {
    if (!p.getAttribute('normal')) p.computeVertexNormals();
    if (!p.getAttribute('uv')) {
      p.setAttribute('uv', new BufferAttribute(new Float32Array(p.getAttribute('position').count * 2), 2));
    }
    vcount += p.getAttribute('position').count;
    icount += p.getIndex() ? p.getIndex()!.count : p.getAttribute('position').count;
  }

  const position = new Float32Array(vcount * 3);
  const normal = new Float32Array(vcount * 3);
  const uv = new Float32Array(vcount * 2);
  const index = vcount > 65535 ? new Uint32Array(icount) : new Uint16Array(icount);

  let vo = 0;
  let io = 0;
  for (const p of parts) {
    const pp = p.getAttribute('position') as BufferAttribute;
    const pn = p.getAttribute('normal') as BufferAttribute;
    const pu = p.getAttribute('uv') as BufferAttribute;
    position.set(pp.array as Float32Array, vo * 3);
    normal.set(pn.array as Float32Array, vo * 3);
    uv.set(pu.array as Float32Array, vo * 2);
    const pi = p.getIndex();
    if (pi) {
      for (let i = 0; i < pi.count; i++) index[io + i] = pi.getX(i) + vo;
      io += pi.count;
    } else {
      for (let i = 0; i < pp.count; i++) index[io + i] = i + vo;
      io += pp.count;
    }
    vo += pp.count;
    p.dispose();
  }

  const g = new BufferGeometry();
  g.setAttribute('position', new BufferAttribute(position, 3));
  g.setAttribute('normal', new BufferAttribute(normal, 3));
  g.setAttribute('uv', new BufferAttribute(uv, 2));
  g.setIndex(new BufferAttribute(index, 1));
  return g;
}

// ─────────────────────────────────────────────────────────────────────────────
// Chunked mesh builder
// ─────────────────────────────────────────────────────────────────────────────

interface Bucket {
  key: string;
  preset: RampName;
  opts: CelOptions;
  chunk: number;
  parts: BufferGeometry[];
}

interface BuiltChunk {
  group: Object3D;
  chunk: number;
}

/** Metres of route distance per visibility chunk. */
const CHUNK_METRES = 220;

export class MeshBuilder {
  private buckets = new Map<string, Bucket>();
  private built: BuiltChunk[] = [];
  private materials: CelMaterial[] = [];
  private geometries: BufferGeometry[] = [];
  private visibleRange = Infinity;

  constructor(readonly object: Object3D) {}

  /**
   * Queue a geometry. `tag` selects the material bucket, so two calls with the
   * same tag must want the same preset AND the same options.
   */
  add(geo: BufferGeometry, preset: RampName, tag: string, routeDistance: number, opts: CelOptions = {}): void {
    const chunk = Math.max(0, Math.floor(routeDistance / CHUNK_METRES));
    const key = `${tag}#${chunk}`;
    let b = this.buckets.get(key);
    if (!b) {
      b = { key, preset, opts, chunk, parts: [] };
      this.buckets.set(key, b);
    }
    b.parts.push(geo);
  }

  build(): void {
    for (const b of this.buckets.values()) {
      if (b.parts.length === 0) continue;
      const geo = mergeGeos(b.parts);
      // Hard-surface weld: creases sharper than 78 degrees stay sharp, so a
      // rail's cap does not smear into its tube.
      finalizeGeometry(geo, { tolerance: 5e-4, maxWeldAngle: 78, ao: true, aoStrength: 0.5 });
      const name = b.key.replace('#', '-');
      const built = makeCelMesh(geo, b.preset, { vertexAo: true, ...b.opts, name });
      built.mesh.castShadow = true;
      built.mesh.receiveShadow = true;
      this.materials.push(built.material);
      this.geometries.push(geo);
      this.object.add(built.group);
      this.built.push({ group: built.group, chunk: b.chunk });
    }
    this.buckets.clear();
  }

  /** Show only the chunks within `range` metres of route distance `d`. */
  setWindow(d: number, range: number): void {
    if (range === this.visibleRange && range === Infinity) return;
    this.visibleRange = range;
    const c = d / CHUNK_METRES;
    const span = range / CHUNK_METRES + 1;
    for (let i = 0; i < this.built.length; i++) {
      const b = this.built[i];
      b.group.visible = Math.abs(b.chunk + 0.5 - c) <= span;
    }
  }

  dispose(): void {
    for (const m of this.materials) disposeCelMaterial(m);
    for (const g of this.geometries) g.dispose();
    this.materials.length = 0;
    this.geometries.length = 0;
    this.built.length = 0;
    this.object.clear();
  }
}

